export function Icon({
  name,
  size = 20,
  color,
  weight = 'regular',
  ...props
}: { name: IconName; size?: number; color?: string; weight?: IconWeight } & Omit<
  SvgProps,
  'color' | 'width' | 'height'
>) {
  const IconComponent = iconMap[name] || IconInfoCircle;
  const strokeWidth = weight === 'thin' ? 1.5 : weight === 'bold' ? 2.5 : 2;
  return (
    <IconComponent width={size} height={size} color={color} strokeWidth={strokeWidth} {...props} />
  );
}
