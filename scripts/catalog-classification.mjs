export function applyReviewedClassification(exercise) {
  const next = { ...exercise };
  if (staticMobilityIds.has(next.id)) next.trackingType = 'duration';
  if (dynamicMobilityIds.has(next.id)) {
    next.trackingType = 'reps-only';
    next.movementPattern = 'mobility';
  }
  if (next.category === 'plyometrics') {
    next.mechanics = 'power';
    if (next.primaryEquipment === 'none') next.trackingType = 'reps-only';
    if (next.primaryEquipment === 'medicine-ball') next.movementPattern = 'throw';
  }
  if (runningDrillTracking[next.id]) {
    Object.assign(next, {
      category: 'cardio',
      workoutTypeIds: ['cardio'],
      trackingType: runningDrillTracking[next.id],
      movementPattern: 'locomotion',
      mechanics: 'cardio',
      bodyRegion: 'cardio',
    });
  }
  Object.assign(next, classificationOverrides[next.id]);
  const equipment = equipmentOverrides[next.id];
  if (equipment) Object.assign(next, { primaryEquipment: equipment, equipment: [equipment] });
  return next;
}
